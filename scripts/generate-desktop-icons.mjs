// Serialize only trusted static SVG primitives; do not introduce runtime HTML injection.
function jsx(node) {
  if (node === null || node === undefined || node === false) return '';
  if (Array.isArray(node)) return node.map(jsx).join('');
  if (!isValidElement(node)) throw new Error('Expected a static Phosphor SVG element');
  const { children, ...props } = node.props;
  if (node.type === Fragment) return '<>' + jsx(children) + '</>';
  if (
    !['path', 'g', 'rect', 'circle', 'ellipse', 'line', 'polyline', 'polygon'].includes(node.type)
  )
    throw new Error('Unexpected SVG primitive: ' + String(node.type));
  const attrs = Object.entries(props)
    .map(([key, value]) => {
      if (
        !/^[a-zA-Z]+$/.test(key) ||
        key.startsWith('on') ||
        !['string', 'number'].includes(typeof value)
      )
        throw new Error('Unexpected SVG attribute: ' + key);
      return ' ' + key + '={' + JSON.stringify(value) + '}';
    })
    .join('');
  return children
    ? '<' + node.type + attrs + '>' + jsx(children) + '</' + node.type + '>'
    : '<' + node.type + attrs + ' />';
}

const version = JSON.parse(readFileSync(resolve(phosphor, 'package.json'), 'utf8')).version;
const license = readFileSync(resolve(phosphor, 'LICENSE'), 'utf8').trim();
let output =
  '/*! Generated by scripts/generate-desktop-icons.mjs from Phosphor ' +
  version +
  '.\n' +
  license +
  '\n*/\n';
for (const [alias, name] of Object.entries(selected)) {
  const { default: weights } = await import(
    pathToFileURL(resolve(phosphor, 'dist/defs', name + '.es.js')).href
  );
  output += 'export const ' + alias + 'Glyph = { regular: (' + jsx(weights.get('regular')) + ')';
  if (bold.has(alias)) output += ', bold: (' + jsx(weights.get('bold')) + ')';
  output += ' };\n';
}
const target = resolve(root, 'apps/desktop/src/iconPaths.tsx');
const config = await prettier.resolveConfig(target);
output = await prettier.format(output, { ...config, parser: 'typescript' });
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output)
    throw new Error('Icon paths are stale; run node scripts/generate-desktop-icons.mjs');
} else writeFileSync(target, output);
console.log(
  'Phosphor ' +
    version +
    ': ' +
    Object.keys(selected).length +
    ' regular and ' +
    bold.size +
    ' bold glyphs verified.',
);
